#!/usr/bin/env bash
# Prints the Homebrew cask for a release: scripts/make-cask.sh <version> <sha256 of TitleSwitcher.zip>
# CI writes the output to Casks/title-switcher.rb in aasp-dev/homebrew-tap.
set -euo pipefail
version="${1:?usage: make-cask.sh <version> <sha256>}"
sha256="${2:?usage: make-cask.sh <version> <sha256>}"
cat <<CASK
cask "title-switcher" do # Generated by scripts/make-cask.sh in aasp-dev/title-switcher
  version "${version}"
  sha256 "${sha256}"

  url "https://github.com/aasp-dev/title-switcher/releases/download/v#{version}/TitleSwitcher.zip"
  name "TitleSwitcher"
  desc "Keyboard-driven window switcher that searches window titles"
  homepage "https://github.com/aasp-dev/title-switcher"

  depends_on macos: :sonoma

  app "TitleSwitcher.app"

  # The app is not notarized, so clear the quarantine flag Gatekeeper would otherwise block it on.
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/TitleSwitcher.app"], must_succeed: false
  end

  uninstall quit: "dev.local.TitleSwitcher"
end
CASK
